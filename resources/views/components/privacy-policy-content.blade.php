            </div>

            <div class="space-y-3">
                <h3 class="font-bold text-gray-900 dark:text-white flex items-center gap-2">
                    <span class="w-1.5 h-4 bg-[#0B5694] dark:bg-blue-500 rounded-full"></span> For Security Purposes:
                </h3>
                <ul class="list-disc list-inside space-y-2 pl-4 text-sm font-semibold text-gray-600 dark:text-gray-300">
                    <li>Login records and the device used (kept for 90 days)</li>
                    <li>Pages you visited during a session (kept for 90 days)</li>
                </ul>
            </div>
        </div>
    </section>

    {{-- 4. What We Will Never Collect --}}
    <section id="section-4" class="space-y-6 scroll-mt-6">
        <div class="border-b border-gray-100 dark:border-gray-800 pb-3">
            <h2 class="text-lg font-bold text-gray-900 dark:text-white uppercase tracking-tight">4. What We Will Never Collect</h2>
        </div>
        <div class="space-y-4">
            <p>SmarTern does not collect any of the following:</p>
            <ul class="list-disc list-inside space-y-2 pl-4 text-sm font-semibold text-gray-600 dark:text-gray-300">
                <li>Government ID numbers (SSS, PhilHealth, TIN, passport, etc.)</li>
                <li>Bank details or financial information</li>
                <li>Fingerprints, facial scans, or other biometric data</li>
                <li>Medical or health records</li>
                <li>Political views, religious beliefs, or sexual orientation</li>
                <li>Data from your social media accounts</li>
            </ul>
        </div>
    </section>

    {{-- 5. Why Do We Use Your Information? --}}
    <section id="section-5" class="space-y-6 scroll-mt-6">
        <div class="border-b border-gray-100 dark:border-gray-800 pb-3">
            <h2 class="text-lg font-bold text-gray-900 dark:text-white uppercase tracking-tight">5. Why Do We Use Your Information?</h2>
        </div>
        <div class="space-y-4">
            <p>We use your information only to run the internship program. This includes:</p>
            <ul class="list-disc list-inside space-y-2 pl-4 text-sm font-semibold text-gray-600 dark:text-gray-300">
                <li>Setting up and managing your account</li>
                <li>Matching you with an appropriate office for your internship</li>
                <li>Tracking your attendance and daily tasks</li>
                <li>Issuing your certificate when you complete the program</li>
                <li>Keeping the system secure and detecting unusual activity</li>
                <li>Sending you updates and notifications about your internship</li>
                <li>Generating summary reports for program management</li>
            </ul>
            <p class="text-sm font-semibold text-amber-600 dark:text-amber-400">
                Note: If you do not provide the required information, SDO QC may not be able to process your internship application.
            </p>
        </div>
    </section>

    {{-- 6. Who Can See Your Information? --}}
    <section id="section-6" class="space-y-6 scroll-mt-6">
        <div class="border-b border-gray-100 dark:border-gray-800 pb-3">
            <h2 class="text-lg font-bold text-gray-900 dark:text-white uppercase tracking-tight">6. Who Can See Your Information?</h2>
        </div>
        <div class="space-y-4">
            <p>Only the people who need to see your information for their role can access it:</p>
            <ul class="list-disc list-inside space-y-2 pl-4 text-sm font-semibold text-gray-600 dark:text-gray-300">
                <li><strong>Student Interns:</strong> can only see their own profile, attendance, tasks, and placement</li>
                <li><strong>School Coordinators:</strong> can only see interns from their own school</li>
                <li><strong>Office Supervisors:</strong> can only see interns assigned to their office</li>
                <li><strong>Head Supervisor:</strong> can view overall program summaries and reports</li>
                <li><strong>IT Administrators:</strong> can access system security records but cannot read the content of your task remarks or full assessment answers</li>
            </ul>
        </div>
    </section>

    {{-- 7. Do We Share Your Information with Others? --}}
    <section id="section-7" class="space-y-6 scroll-mt-6">
        <div class="border-b border-gray-100 dark:border-gray-800 pb-3">
            <h2 class="text-lg font-bold text-gray-900 dark:text-white uppercase tracking-tight">7. Do We Share Your Information with Others?</h2>
        </div>
        <div class="space-y-4">
            <p>SDO QC will never sell or share your information for commercial purposes. Your data may only be shared in these situations:</p>
            <ul class="list-disc list-inside space-y-2 pl-4 text-sm font-semibold text-gray-600 dark:text-gray-300">
                <li>When required by Philippine law or a government order</li>
                <li>When required by the National Privacy Commission</li>
                <li>With technical service providers (such as hosting companies) who help run the system, under a signed agreement that requires them to follow the same privacy standards</li>
                <li>With your explicit written consent for any other purpose</li>
            </ul>
        </div>
    </section>

    {{-- 8. How Do We Keep Your Information Safe? --}}
    <section id="section-8" class="space-y-6 scroll-mt-6">
        <div class="border-b border-gray-100 dark:border-gray-800 pb-3">
            <h2 class="text-lg font-bold text-gray-900 dark:text-white uppercase tracking-tight">8. How Do We Keep Your Information Safe?</h2>
        </div>
        <div class="space-y-4">
            <p>We use a range of security measures to protect your data, including:</p>
            <ul class="list-disc list-inside space-y-2 pl-4 text-sm font-semibold text-gray-600 dark:text-gray-300">
                <li>All data sent between you and SmarTern is encrypted so it cannot be read by others</li>
                <li>The database and all backups are stored in an encrypted form</li>
                <li>Your password is converted into an unreadable code - it is never stored as plain text</li>
                <li>Admins and head supervisors must verify their identity with a second step when logging in</li>
                <li>Your session automatically ends after 30 minutes of no activity</li>
                <li>Your exact GPS location is deleted within 24 hours of each attendance scan</li>
                <li>Each person can only access data their role allows—no one can view data outside their permission level</li>
                <li>Every login and data access is recorded in a permanent log</li>
            </ul>
        </div>
    </section>

    {{-- 9. How Long Do We Keep Your Information? --}}
    <section id="section-9" class="space-y-6 scroll-mt-6">
        <div class="border-b border-gray-100 dark:border-gray-800 pb-3">
            <h2 class="text-lg font-bold text-gray-900 dark:text-white uppercase tracking-tight">9. How Long Do We Keep Your Information?</h2>
        </div>
        <div class="space-y-4">
            <p>We keep your data only for as long as needed:</p>
            <ul class="list-disc list-inside space-y-2 pl-4 text-sm font-semibold text-gray-600 dark:text-gray-300">
                <li><strong>Profile and account details:</strong> until your account is closed, plus 1 year</li>
                <li><strong>Attendance records:</strong> until your internship ends, plus 1 year</li>
                <li><strong>Your exact GPS location:</strong> deleted within 24 hours</li>
                <li><strong>Task records:</strong> until your internship ends, plus 1 year</li>
                <li><strong>Placement records:</strong> until your internship ends, plus 3 years</li>
                <li><strong>Certificate records:</strong> kept for at least 5 years, as required by government records rules</li>
                <li><strong>Login and session records:</strong> 90 days, then automatically deleted</li>
            </ul>
        </div>
    </section>

    {{-- 10. What About Automated Tools? --}}
    <section id="section-10" class="space-y-6 scroll-mt-6">
        <div class="border-b border-gray-100 dark:border-gray-800 pb-3">
            <h2 class="text-lg font-bold text-gray-900 dark:text-white uppercase tracking-tight">10. What About Automated Tools?</h2>
        </div>
        <div class="space-y-4">
            <p>SmarTern uses two automated tools to assist with decisions, but neither tool ever makes a final decision on its own. A real person always reviews and confirms any outcome.</p>
            <ul class="list-disc list-inside space-y-3 pl-4 text-sm font-semibold text-gray-600 dark:text-gray-300">
                <li><strong>Matching Tool:</strong> suggests which office best fits a student's skills. Coordinators and supervisors review the suggestion before any placement is confirmed.</li>
                <li><strong>Activity Checker:</strong> flags unusual login or scan patterns for an admin to review. A flag only means something looks different from normal—it is not an accusation of wrongdoing.</li>
            </ul>
            <p class="text-sm font-semibold text-amber-600 dark:text-amber-400">
                Note: If your account is flagged, you will receive a notification. You will have 5 business days to send a written explanation. No action can be taken against you until a human review is completed.
            </p>
        </div>
    </section>

    {{-- 11. What Are Your Rights? --}}
    <section id="section-11" class="space-y-6 scroll-mt-6">
        <div class="border-b border-gray-100 dark:border-gray-800 pb-3">
            <h2 class="text-lg font-bold text-gray-900 dark:text-white uppercase tracking-tight">11. What Are Your Rights?</h2>
        </div>
        <div class="space-y-4">
            <p>Under the Data Privacy Act of 2012, you have the right to:</p>
            <ul class="list-disc list-inside space-y-2 pl-4 text-sm font-semibold text-gray-600 dark:text-gray-300">
                <li><strong>Be informed:</strong> know what data we collect and why (this Statement is how we do that)</li>
                <li><strong>Access your data:</strong> request a copy of your information; we will respond within 15 business days</li>
                <li><strong>Correct mistakes:</strong> update wrong or outdated information in your profile settings, or by written request</li>
                <li><strong>Have your data deleted:</strong> ask us to remove your data when it is no longer needed (some records must be kept by law)</li>
                <li><strong>Object to certain uses:</strong> say no to specific uses of your data, such as being included in program reports</li>
                <li><strong>Take your data elsewhere:</strong> request your information in a format you can transfer to another system</li>
                <li><strong>File a complaint:</strong> report a concern to the National Privacy Commission if you believe your rights have been violated</li>
            </ul>
            <p class="text-sm font-semibold text-gray-600 dark:text-gray-300">
                To exercise any of these rights, submit a written request to the Head Supervisor.
            </p>
        </div>
    </section>

    {{-- 12. How Do You Give or Withdraw Consent? --}}
    <section id="section-12" class="space-y-6 scroll-mt-6">
        <div class="border-b border-gray-100 dark:border-gray-800 pb-3">
            <h2 class="text-lg font-bold text-gray-900 dark:text-white uppercase tracking-tight">12. How Do You Give or Withdraw Consent?</h2>
        </div>
        <div class="space-y-4">
            <p>
                When you register, you will be shown this Statement in full. You must tick a box to confirm you have read and agreed to it before your account is created. Your agreement is saved with a timestamp.
            </p>
            <p>
                You can withdraw your consent at any time by writing to SDO QC's Data Protection Officer. Your account will be deactivated, but this will not affect your internship record, rendered hours, or certificate.
            </p>
        </div>
    </section>

