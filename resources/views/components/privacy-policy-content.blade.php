    </section>

    {{-- 14. What If There Is a Data Breach? --}}
    <section id="section-14" class="space-y-6 scroll-mt-6">
        <div class="border-b border-gray-100 dark:border-gray-800 pb-3">
            <h2 class="text-lg font-bold text-gray-900 dark:text-white uppercase tracking-tight">14. What If There Is a Data Breach?</h2>
        </div>
        <div class="space-y-4">
            <p>If your personal information is ever exposed without authorization, SDO QC will:</p>
            <ul class="list-disc list-inside space-y-2 pl-2 text-sm font-semibold text-gray-600 dark:text-gray-300">
                <li>Stop the breach and assess what happened within 24 hours</li>
                <li>Notify affected users within 72 hours if their information is at risk</li>
                <li>Report to the National Privacy Commission within 72 hours as required by law</li>
                <li>Document the incident and update security controls to prevent it from happening again</li>
            </ul>
            <p class="text-sm font-semibold text-amber-600 dark:text-amber-400">
                You will always be told what happened, what data was involved, and what steps were taken.
            </p>
