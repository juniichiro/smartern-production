                    <li>Your location at the time of scanning (used only to confirm that you are on-site; GPS data is not stored and is used solely for this verification)</li>
                    <li>Tasks assigned to you, whether you completed them, and any supervisor remarks</li>
                    <li>Your skills self-assessment answers submitted during application</li>
                    <li>Your internship placement, certificate, and notification records</li>
