                    <li>Your full name, age, and date of birth</li>
                    <li>Your mobile number and email address</li>
                    <li>Your school, department, and program</li>
                    <li>Your profile photo (optional)</li>
                    <li>Your username and password (your password is never stored in readable form)</li>
                </ul>
            </div>

            <div class="space-y-3">
                <h3 class="font-bold text-gray-900 dark:text-white flex items-center gap-2">
                    <span class="w-1.5 h-4 bg-[#0B5694] dark:bg-blue-500 rounded-full"></span> During the Internship:
