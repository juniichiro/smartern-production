    {{-- 1. What is SmarTern? --}}
    <section id="section-1" class="space-y-6 scroll-mt-6">
        <div class="border-b border-gray-100 dark:border-gray-800 pb-3">
            <h2 class="text-lg font-bold text-gray-900 dark:text-white uppercase tracking-tight">1. What is SmarTern?</h2>
        </div>
        <div class="space-y-4">
            <p>
                SmarTern is an online platform managed by the Schools Division Office of Quezon City (SDO QC). It handles student internship programs from matching students with offices, tracking attendance and tasks, to issuing completion certificates.
            </p>
            <p>
                This Statement covers everyone who uses SmarTern: Student Interns, School Coordinators, Office Supervisors, Head Supervisors, and IT Administrators.
            </p>
        </div>
    </section>

    {{-- 2. Who is Responsible for Your Information? --}}
    <section id="section-2" class="space-y-6 scroll-mt-6">
        <div class="border-b border-gray-100 dark:border-gray-800 pb-3">
            <h2 class="text-lg font-bold text-gray-900 dark:text-white uppercase tracking-tight">2. Who is Responsible for Your Information?</h2>
        </div>
        <div class="space-y-4">
            <p>
                SDO Quezon City is responsible for all personal data collected through SmarTern. They decide how your information is used and make sure it is handled in line with the Data Privacy Act of 2012.
            </p>
            <p>
                The system was built by the Lumiere Research Group of FEU Institute of Technology, but they have no access to your data once SmarTern is handed over to SDO QC.
            </p>
        </div>
    </section>

